from __future__ import annotations

"""tests/capture_golden.py — Golden fixture generator for the behavior-preservation tests.

NOT a pytest test file. Run from the repo root to regenerate tests/fixtures/golden_scores.json:

    python tests/capture_golden.py

Everything it reads is synthetic: tests/fixtures/synthetic_pool.jsonl (generated by
scripts/gen_synthetic_fixtures.py with seed 42), the invented judge scores beside it, and the
synthetic baselines built from them by scripts/build_baselines.py. Waste entries are not stored:
they are produced here by running the real detectors (tracegauge.waste.build_waste_entry) over
each fixture digest.

Selects up to 20 sessions that together cover the (band_verdict x judge_present x
waste_events_present) combinations present in the pool: one per cell first, then a second per
cell. Serialises the full EfficiencyResult plus the raw inputs used, so
test_behavior_preservation.py can reconstruct each call exactly. Review the output before
committing it: the file is a frozen record of what the scorer returned, not a specification.
"""

import json
import sys
from pathlib import Path

# ---------------------------------------------------------------------------
# Make scripts/ and the package importable (mirrors pattern in test_waste_detectors.py line 14)
# ---------------------------------------------------------------------------
REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "scripts"))
sys.path.insert(0, str(REPO_ROOT))

from efficiency_score import EfficiencyResult, load_baselines, score_session  # noqa: E402
from tracegauge.waste import build_waste_entry  # noqa: E402

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
FIXTURES_DIR = REPO_ROOT / "tests" / "fixtures"
POOL_ADAPTED_PATH = FIXTURES_DIR / "synthetic_pool.jsonl"
JUDGE_SCORES_PATH = FIXTURES_DIR / "synthetic_judge_scores.jsonl"
BASELINES_PATH = FIXTURES_DIR / "baselines_synthetic.json"
OUTPUT_PATH = FIXTURES_DIR / "golden_scores.json"

MAX_GOLDEN = 20
MAX_PER_GROUP = 2


# ---------------------------------------------------------------------------
# Loader helpers
# ---------------------------------------------------------------------------


def _load_jsonl_index(path: Path) -> dict[str, dict]:
    """Load a JSONL file and return a dict keyed by session_id."""
    index: dict[str, dict] = {}
    with path.open("r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                entry = json.loads(line)
                index[entry["session_id"]] = entry
    return index


def _load_pool_index() -> dict[str, dict]:
    """Load the synthetic pool and return a dict keyed by session_id."""
    return _load_jsonl_index(POOL_ADAPTED_PATH)


# ---------------------------------------------------------------------------
# Serialise EfficiencyResult to a plain dict (JSON-safe)
# ---------------------------------------------------------------------------


def _result_to_dict(
    result: EfficiencyResult,
    judge_entry: dict | None,
    waste_entry: dict | None,
) -> dict:
    """Serialise an EfficiencyResult plus its raw call inputs to a JSON-safe dict."""
    return {
        "session_id": result.session_id,
        "task_type": result.task_type,
        "real_tokens": result.real_tokens,
        "scope_status": result.scope_status,
        "baseline_available": result.baseline_available,
        "p25": result.p25,
        "p75": result.p75,
        "median": result.median,
        "band_verdict": result.band_verdict,
        "interpretation": result.interpretation,
        "judge_verdict": result.judge_verdict,
        "judge_score": result.judge_score,
        "judge_reasoning": result.judge_reasoning,
        "waste_event_count": result.waste_event_count,
        "waste_events": result.waste_events,
        # Raw inputs stored so tests can reconstruct the call exactly
        "_input_judge_entry": judge_entry,
        "_input_waste_entry": waste_entry,
    }


# ---------------------------------------------------------------------------
# Group key for stratified sampling
# ---------------------------------------------------------------------------


def _group_key(result: EfficiencyResult) -> tuple[str, bool, bool]:
    """Return a (band_verdict, judge_present, waste_present) tuple for stratification."""
    return (
        result.band_verdict,
        result.judge_verdict is not None,
        result.waste_event_count > 0,
    )


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def main() -> None:
    """Generate tests/fixtures/golden_scores.json from the synthetic pool."""
    print("Loading synthetic fixtures ...")
    pool_index = _load_pool_index()
    judge_index = _load_jsonl_index(JUDGE_SCORES_PATH)
    baselines = load_baselines(BASELINES_PATH)

    # Score every session. The waste entry comes from the real detectors over the fixture
    # digest, never from a stored file, so fixtures cannot drift from detector behaviour.
    all_results: list[tuple[EfficiencyResult, dict | None, dict | None]] = []
    for session_id, record in pool_index.items():
        je = judge_index.get(session_id)
        we = build_waste_entry(session_id, record["digest"]["turns"])
        result = score_session(record, baselines, judge_entry=je, waste_entry=we)
        all_results.append((result, je, we))

    print(f"  pool sessions : {len(pool_index)}")
    print(f"  judge entries : {len(judge_index)}")
    print(f"  with waste    : {sum(1 for r, _, _ in all_results if r.waste_event_count)}")

    # Stratified sampling: one per (band_verdict x judge x waste) cell, then a second per cell,
    # in pool order, until MAX_GOLDEN.
    group_counts: dict[tuple[str, bool, bool], int] = {}
    selected: list[dict] = []
    chosen: set[str] = set()

    for round_no in range(MAX_PER_GROUP):
        for result, je, we in all_results:
            if len(selected) >= MAX_GOLDEN:
                break
            key = _group_key(result)
            if result.session_id in chosen or group_counts.get(key, 0) != round_no:
                continue
            selected.append(_result_to_dict(result, je, we))
            chosen.add(result.session_id)
            group_counts[key] = round_no + 1

    # Write fixture (LF on every platform, like the rest of the tree)
    FIXTURES_DIR.mkdir(parents=True, exist_ok=True)
    with OUTPUT_PATH.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(selected, indent=2) + "\n")
    print(f"\nWrote {len(selected)} golden entries to {OUTPUT_PATH}")

    # Coverage summary
    print("\nCoverage summary (band_verdict x judge_present x waste_present):")
    header = f"  {'band_verdict':<14}  {'judge_present':<14}  {'waste_present':<14}  count"
    print(header)
    print("  " + "-" * (len(header) - 2))
    for key, count in sorted(group_counts.items()):
        band, judge_p, waste_p = key
        print(f"  {band:<14}  {str(judge_p):<14}  {str(waste_p):<14}  {count}")

    print(f"\nTotal unique cells covered: {len(group_counts)}")


if __name__ == "__main__":
    main()
